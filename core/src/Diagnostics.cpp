void setDiagnosticLanguage(DiagnosticLanguage value) noexcept {
    language.store(value, std::memory_order_relaxed);
}

DiagnosticLanguage diagnosticLanguage() noexcept {
    return language.load(std::memory_order_relaxed);
}

const char* diagnostic(const char* source) noexcept {
    if (!source) return "";
    if (diagnosticLanguage() == DiagnosticLanguage::English) {
        for (const auto& entry : translations)
            if (entry.source == source) return entry.english.data();
    }
    return source;
}

std::span<const DiagnosticTranslation> diagnosticCatalog() noexcept {
    return translations;
}

